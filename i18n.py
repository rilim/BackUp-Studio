def translate(text, language="lt"):
    """Translate a UI message. Unknown strings (including filenames) are preserved."""
    if language != "en" or not isinstance(text, str):
        return text
    if text in EN:
        return EN[text]
    for source, target in sorted(FRAGMENTS.items(), key=lambda pair: len(pair[0]), reverse=True):
        # Only message fragments are replaced. Never rewrite arbitrary file names.
        if source in text:
            text = text.replace(source, target)
    return text
